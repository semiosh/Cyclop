import AppKit

/// Minimal platform boundary so history policies can be verified without
/// reading the user's pasteboard or requiring a WindowServer in tests.
@MainActor
protocol ClipboardAccess: AnyObject {
    var changeCount: Int { get }
    func availableType(from types: [NSPasteboard.PasteboardType]) -> NSPasteboard.PasteboardType?
    func data(forType type: NSPasteboard.PasteboardType) -> Data?
    func string(forType type: NSPasteboard.PasteboardType) -> String?
    func readObjects(forClasses classes: [AnyClass], options: [NSPasteboard.ReadingOptionKey: Any]?) -> [Any]?
    @discardableResult func clearContents() -> Int
    @discardableResult func setData(_ data: Data?, forType type: NSPasteboard.PasteboardType) -> Bool
    @discardableResult func setString(_ string: String, forType type: NSPasteboard.PasteboardType) -> Bool
    @discardableResult func writeObjects(_ objects: [NSPasteboardWriting]) -> Bool
}

extension NSPasteboard: ClipboardAccess {}

struct ClipItem: Identifiable, Equatable {
    enum Payload: Equatable {
        case text(String)
        case file(URL)
        case image(Data)
    }

    let id = UUID()
    let payload: Payload
    let date: Date

    var preview: String {
        switch payload {
        case .text(let string):
            return string.trimmingCharacters(in: .whitespacesAndNewlines)
        case .file(let url):
            return url.lastPathComponent
        case .image:
            return localized("Image")
        }
    }

    var symbol: String {
        switch payload {
        case .text(let string):
            if string.hasPrefix("http://") || string.hasPrefix("https://") { return "link" }
            return "text.alignleft"
        case .file:
            return "doc"
        case .image:
            return "photo"
        }
    }

    static func == (lhs: ClipItem, rhs: ClipItem) -> Bool { lhs.payload == rhs.payload }
}

/// Polls the general pasteboard's change counter. Cheap: one integer read
/// twice a second, and nothing at all is read until the counter moves.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published var isPaused: Bool {
        didSet {
            lastChangeCount = pasteboard.changeCount
            generation += 1
            onPauseChanged?(isPaused)
        }
    }
    var onPauseChanged: ((Bool) -> Void)?
    var retention: TimeInterval = 900 {
        didSet { expire() }
    }
    private let pasteboard: any ClipboardAccess
    private let clock: () -> Date
    private var generation = 0
    private var isRunning = false
    private var sessionObservers: [Any] = []
    private var sessionActive = true
    private var screensAwake = true

    func setSessionActive(_ active: Bool) {
        sessionActive = active
        clear()
    }

    private func setScreensAwake(_ awake: Bool) {
        screensAwake = awake
        clear()
    }

    init(pasteboard: any ClipboardAccess = NSPasteboard.general, clock: @escaping () -> Date = Date.init, paused: Bool = false) {
        self.pasteboard = pasteboard
        self.clock = clock
        self.isPaused = paused
        lastChangeCount = pasteboard.changeCount
    }

    /// Retention applies to collection time even when an old entry is copied.
    func expire() {
        guard retention > 0 else { return }
        let cutoff = clock().addingTimeInterval(-retention)
        if items.contains(where: { $0.date <= cutoff }) {
            items.removeAll { $0.date <= cutoff }
        }
    }

    /// Raised for image data on the pasteboard — a screenshot taken straight to
    /// the clipboard, which would otherwise vanish after one paste.
    var onImage: ((Data) -> Void)?

    /// Reading images into memory is independent of the optional disk archive.
    /// This hook also cancels pending Universal Clipboard image reads.
    var wantsImages: () -> Bool = { true }

    private var timer: Timer?
    private var lastChangeCount: Int
    private let limit = 40
    private let memoryLimit = 64 * 1024 * 1024
    /// Types an app sets to keep a copy out of history tools. Presence is what
    /// counts, not content: a type can be declared with data that is still on
    /// its way, and asking for the bytes would then answer nil for a password
    /// that is about to arrive. `ConcealedType` is what password managers set;
    /// the other two mark copies made by a machine rather than by a hand.
    private let optOut: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    func start() {
        stop()
        isRunning = true
        // Do not collect what was copied while this feature was disabled.
        lastChangeCount = pasteboard.changeCount
        let center = NSWorkspace.shared.notificationCenter
        for (name, active) in [(NSWorkspace.sessionDidResignActiveNotification, false),
                               (NSWorkspace.sessionDidBecomeActiveNotification, true)] {
            sessionObservers.append(center.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { self?.setSessionActive(active) }
            })
        }
        for (name, awake) in [(NSWorkspace.screensDidSleepNotification, false),
                              (NSWorkspace.screensDidWakeNotification, true)] {
            sessionObservers.append(center.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { self?.setScreensAwake(awake) }
            })
        }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        // The half-second is a ceiling, not a beat: nobody notices a copy
        // landing in history a fifth of a second late, and the slack lets the
        // system fold this wake-up into others.
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        isRunning = false
        generation += 1
        for observer in sessionObservers { NSWorkspace.shared.notificationCenter.removeObserver(observer) }
        sessionObservers.removeAll()
        clear()
        timer?.invalidate()
        timer = nil
    }

    func clear() {
        generation += 1
        lastChangeCount = pasteboard.changeCount
        items.removeAll()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
    }

    /// Puts an entry back on the pasteboard without re-recording it.
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.payload {
        case .text(let string):
            pasteboard.setString(string, forType: .string)
        case .file(let url):
            pasteboard.writeObjects([url as NSURL])
        case .image(let png):
            pasteboard.setData(png, forType: .png)
            pasteboard.setData(Data(), forType: .cyclopInternal)
        }
        lastChangeCount = pasteboard.changeCount
        // Freshly used entries bubble to the top.
        if let index = items.firstIndex(where: { $0.id == item.id }), index != 0 {
            items.remove(at: index)
            items.insert(item, at: 0)
        }
    }

    func poll() {
        expire()
        guard !isPaused, sessionActive, screensAwake else {
            lastChangeCount = pasteboard.changeCount
            return
        }
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        guard pasteboard.availableType(from: optOut) == nil else { return }
        // Our own write — copying a screenshot back out of the shelf must not
        // save it to disk all over again.
        guard pasteboard.data(forType: .cyclopInternal) == nil else { return }

        // A copied file arrives as a URL, not as image data, so URLs win first.
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [URL],
           let url = urls.first {
            record(ClipItem(payload: .file(url), date: clock()))
            return
        }

        if wantsImages() {
            if let png = pngFromPasteboard(pasteboard) {
                receiveImage(png)
                return
            }

            // A copy made on the phone arrives in two parts: macOS puts the
            // type on the pasteboard the moment the phone announces it, and
            // the picture itself is still coming over the air. So the counter
            // can move while there are no bytes to read yet — and reading once
            // would drop the screenshot for good, because the counter has
            // already been marked as seen. Wait for it instead.
            if pasteboard.availableType(from: [.png, .tiff]) != nil {
                awaitImage(at: pasteboard.changeCount, attempt: 0, generation: generation)
                return
            }
        }

        guard let string = pasteboard.string(forType: .string),
              !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        record(ClipItem(payload: .text(string), date: clock()))
    }

    /// Checks back until the promised picture has actually arrived.
    ///
    /// Gives up after a few seconds, and stops the moment the pasteboard moves
    /// on: a copy made in the meantime is the newer intention, and finishing a
    /// transfer the user has already replaced would put the wrong thing on the
    /// shelf.
    private func awaitImage(at changeCount: Int, attempt: Int, generation: Int) {
        guard isRunning, !isPaused, sessionActive, screensAwake, self.generation == generation, wantsImages(),
              pasteboard.availableType(from: optOut) == nil else { return }
        // Out of patience. Something declared a picture and never produced one,
        // so fall back to what else was on the pasteboard — otherwise a copy
        // that merely offered an image alongside its text would go unrecorded.
        guard attempt < 12 else {
            guard pasteboard.changeCount == changeCount,
                  let string = pasteboard.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
            record(ClipItem(payload: .text(string), date: clock()))
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { [weak self] in
            MainActor.assumeIsolated {
                guard let self, self.isRunning, !self.isPaused, self.sessionActive, self.screensAwake, self.generation == generation,
                      self.wantsImages() else { return }
                let pasteboard = self.pasteboard
                guard pasteboard.changeCount == changeCount,
                      pasteboard.availableType(from: self.optOut) == nil else { return }
                if let png = self.pngFromPasteboard(pasteboard) {
                    self.receiveImage(png)
                    return
                }
                self.awaitImage(at: changeCount, attempt: attempt + 1, generation: generation)
            }
        }
    }

    /// Screenshots land as PNG; other apps often offer only TIFF.
    private func pngFromPasteboard(_ pasteboard: any ClipboardAccess) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff),
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private func receiveImage(_ png: Data) {
        guard !png.isEmpty, png.count <= memoryLimit else { return }
        record(ClipItem(payload: .image(png), date: clock()))
        onImage?(png)
    }

    private func byteCount(_ item: ClipItem) -> Int {
        switch item.payload {
        case .image(let data): return data.count
        case .text(let text): return text.utf8.count
        case .file(let url): return url.absoluteString.utf8.count
        }
    }

    private func record(_ item: ClipItem) {
        if case .text(let text) = item.payload, text.utf8.count > 100_000 { return }
        items.removeAll { $0 == item }
        items.insert(item, at: 0)
        if items.count > limit { items.removeLast(items.count - limit) }
        var bytes = items.reduce(0) { $0 + byteCount($1) }
        while bytes > memoryLimit, let oldest = items.last {
            bytes -= byteCount(oldest)
            items.removeLast()
        }
    }
}
