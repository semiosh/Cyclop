import AppKit
import Testing
@testable import Cyclop

/// An in-memory platform adapter keeps these tests independent of WindowServer.
@MainActor
struct ClipboardStoreTests {
    private func write(_ text: String, to board: MemoryClipboard, marker: String? = nil) {
        board.clearContents()
        if let marker { board.setData(Data(), forType: .init(marker)) }
        board.setString(text, forType: .string)
    }

    @Test func ignoresPasswordManagerAndMachineCopies() {
        let board = MemoryClipboard()
        let store = ClipboardStore(pasteboard: board)
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            write("secret", to: board, marker: marker)
            store.poll()
        }
        #expect(store.items.isEmpty)
        write("ordinary copy", to: board)
        store.poll()
        #expect(store.items.count == 1)
    }

    @Test func pauseDoesNotCollectAndResumeDoesNotBackfill() {
        let board = MemoryClipboard()
        let store = ClipboardStore(pasteboard: board)
        store.isPaused = true
        write("while paused", to: board)
        store.poll()
        store.isPaused = false
        store.poll()
        #expect(store.items.isEmpty)
        write("after resume", to: board)
        store.poll()
        #expect(store.items.first?.preview == "after resume")
    }

    @Test func retentionExpiresEvenWithoutAnotherCopy() {
        let board = MemoryClipboard()
        var now = Date(timeIntervalSince1970: 1000)
        let store = ClipboardStore(pasteboard: board, clock: { now })
        store.retention = 900
        write("old", to: board)
        store.poll()
        now.addTimeInterval(901)
        store.poll()
        #expect(store.items.isEmpty)
    }

    @Test func untilQuitPreservesEntriesAndStopClearsThem() {
        let board = MemoryClipboard()
        var now = Date(timeIntervalSince1970: 1000)
        let store = ClipboardStore(pasteboard: board, clock: { now })
        store.retention = 0
        write("entry", to: board)
        store.poll()
        now.addTimeInterval(86400)
        store.poll()
        #expect(store.items.count == 1)
        store.stop()
        #expect(store.items.isEmpty)
    }

    @Test func clearDoesNotImmediatelyRecordCurrentClipboardAgain() {
        let board = MemoryClipboard()
        let store = ClipboardStore(pasteboard: board)
        write("entry", to: board)
        store.poll()
        store.clear()
        store.poll()
        #expect(store.items.isEmpty)
    }

    @Test func sessionInactivityClearsAndSuspendsCapture() {
        let board = MemoryClipboard()
        let store = ClipboardStore(pasteboard: board)
        write("before", to: board)
        store.poll()
        #expect(store.items.count == 1)
        store.setSessionActive(false)
        write("while away", to: board)
        store.poll()
        #expect(store.items.isEmpty)
        store.setSessionActive(true)
        store.poll()
        #expect(store.items.isEmpty)
        write("back", to: board)
        store.poll()
        #expect(store.items.first?.preview == "back")
    }

    @Test(arguments: ["stop", "clear", "pause", "imagesOff"])
    func pendingImageHonorsCancellation(_ action: String) async throws {
        let board = MemoryClipboard()
        let store = ClipboardStore(pasteboard: board)
        var imagesEnabled = true
        var received = 0
        store.wantsImages = { imagesEnabled }
        store.onImage = { _ in received += 1 }
        store.start()
        defer { store.stop() }
        board.clearContents()
        board.promised.insert(.png)
        store.poll()
        switch action {
        case "stop": store.stop()
        case "clear": store.clear()
        case "pause": store.isPaused = true
        default: imagesEnabled = false
        }
        // Promised bytes arrive later without a new pasteboard generation.
        board.setData(Data([1, 2, 3]), forType: .png)
        try await Task.sleep(for: .milliseconds(650))
        #expect(received == 0)
    }

    @Test func screenshotIsKeptInHistoryAndCopiedAsImageWithoutDiskArchive() {
        let board = MemoryClipboard()
        let store = ClipboardStore(pasteboard: board)
        let png = Data(base64Encoded: "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=")!
        board.clearContents()
        board.setData(png, forType: .png)
        store.poll()
        #expect(store.items.count == 1)
        #expect(store.items.first?.payload == .image(png))
        write("next copy", to: board)
        store.poll()
        #expect(store.items.count == 2)
        store.copy(store.items[1])
        #expect(board.data(forType: .png) == png)
        #expect(board.data(forType: .cyclopInternal) != nil)
        store.poll()
        #expect(store.items.count == 2)
        #expect(store.items.first?.payload == .image(png))
    }

    @Test func promisedImageArrivesInHistory() async throws {
        let board = MemoryClipboard()
        let store = ClipboardStore(pasteboard: board)
        store.start()
        defer { store.stop() }
        board.clearContents()
        board.promised.insert(.png)
        store.poll()
        #expect(store.items.isEmpty)
        let png = Data([1, 2, 3])
        board.setData(png, forType: .png)
        try await Task.sleep(for: .milliseconds(650))
        #expect(store.items.count == 1)
        #expect(store.items.first?.payload == .image(png))
    }

    @Test func concealedImagesAreNotRecordedOrArchived() {
        let board = MemoryClipboard()
        let store = ClipboardStore(pasteboard: board)
        var archived = false
        store.onImage = { _ in archived = true }
        board.clearContents()
        board.setData(Data([1, 2, 3]), forType: .png)
        board.setData(Data(), forType: .init("org.nspasteboard.ConcealedType"))
        store.poll()
        #expect(store.items.isEmpty)
        #expect(!archived)
    }

    @Test func imageHistoryHasAMemoryBudget() {
        let board = MemoryClipboard()
        let store = ClipboardStore(pasteboard: board)
        let first = Data(repeating: 1, count: 33 * 1024 * 1024)
        let second = Data(repeating: 2, count: 33 * 1024 * 1024)
        board.clearContents()
        board.setData(first, forType: .png)
        store.poll()
        board.clearContents()
        board.setData(second, forType: .png)
        store.poll()
        #expect(store.items.count == 1)
        #expect(store.items.first?.payload == .image(second))
    }

    @Test func deduplicatesAndBoundsMemory() {
        let board = MemoryClipboard()
        let store = ClipboardStore(pasteboard: board)
        for index in 0..<45 { write("item \(index)", to: board); store.poll() }
        #expect(store.items.count == 40)
        write("item 10", to: board)
        store.poll()
        #expect(store.items.count == 40)
        #expect(store.items.first?.preview == "item 10")
        write(String(repeating: "x", count: 100_001), to: board)
        store.poll()
        #expect(store.items.count == 40)
        #expect(store.items.first?.preview == "item 10")
    }
}

@MainActor
final class MemoryClipboard: ClipboardAccess {
    var changeCount = 0
    private var values: [NSPasteboard.PasteboardType: Data] = [:]
    var promised: Set<NSPasteboard.PasteboardType> = []
    func availableType(from types: [NSPasteboard.PasteboardType]) -> NSPasteboard.PasteboardType? {
        types.first { values[$0] != nil || promised.contains($0) }
    }
    func data(forType type: NSPasteboard.PasteboardType) -> Data? { values[type] }
    func string(forType type: NSPasteboard.PasteboardType) -> String? {
        values[type].flatMap { String(data: $0, encoding: .utf8) }
    }
    func readObjects(forClasses classes: [AnyClass], options: [NSPasteboard.ReadingOptionKey: Any]?) -> [Any]? { nil }
    @discardableResult func clearContents() -> Int {
        values.removeAll()
        promised.removeAll()
        changeCount += 1
        return changeCount
    }
    @discardableResult func setString(_ string: String, forType type: NSPasteboard.PasteboardType) -> Bool {
        values[type] = Data(string.utf8)
        return true
    }
    @discardableResult func setData(_ data: Data?, forType type: NSPasteboard.PasteboardType) -> Bool {
        values[type] = data
        return true
    }
    func writeObjects(_ objects: [NSPasteboardWriting]) -> Bool { true }
}
